// Builds the "ruma" Astryx theme (src/themes/ruma/rumaTheme.ts → ruma.css + ruma.js) with the Astryx CLI, then makes
// the stylesheet work on Safari 16.4–17.3 (the app's oldest supported iOS, docs/design-system.md §업그레이드):
//
// `astryx theme build` wraps every rule in `@scope ([data-astryx-theme="ruma"]) to ([data-astryx-theme])`, and Safari
// only has @scope from 17.4; older versions drop the whole block, so every token would fall back to Astryx's defaults.
// The app has one theme and never nests one, so the scope's lower bound never applies and each block is the same as
// its rules prefixed with `:where([data-astryx-theme="ruma"])` (`:where` keeps the specificity @scope gives them).
// `light-dark()` in the output needs no work here: Vite's CSS minifier (Lightning CSS, target safari16.4) lowers it.
//
// Usage: npm run theme
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = 'src/themes/ruma/rumaTheme.ts'
const CSS = 'src/themes/ruma/ruma.css'

execFileSync('npx', ['astryx', 'theme', 'build', SRC], { stdio: 'inherit' })

/** Index of the `}` matching the `{` at `open`. */
function close(css, open) {
  let depth = 0
  for (let i = open; i < css.length; i++) {
    if (css[i] === '{') depth++
    else if (css[i] === '}' && --depth === 0) return i
  }
  throw new Error('unbalanced braces in ' + CSS)
}

/** Splits a selector list at top-level commas (not those inside `:where(a, b)`). */
function splitList(sel) {
  const parts = []
  let depth = 0
  let start = 0
  for (let i = 0; i < sel.length; i++) {
    if (sel[i] === '(') depth++
    else if (sel[i] === ')') depth--
    else if (sel[i] === ',' && depth === 0) {
      parts.push(sel.slice(start, i).trim())
      start = i + 1
    }
  }
  parts.push(sel.slice(start).trim())
  return parts
}

/** Prefixes each top-level rule of a block body with the scope root; nested at-rules (@media) are handled inside. */
function prefixRules(body, root) {
  let out = ''
  let i = 0
  while (i < body.length) {
    const open = body.indexOf('{', i)
    if (open < 0) {
      out += body.slice(i)
      break
    }
    const end = close(body, open)
    const head = body.slice(i, open)
    const inner = body.slice(open + 1, end)
    const sel = head.trim()
    const lead = head.slice(0, head.length - head.trimStart().length)
    if (sel.startsWith('@')) out += `${lead}${sel} {${prefixRules(inner, root)}}`
    else {
      const prefixed = splitList(sel)
        .map((s) => (s === ':scope' ? root : s.startsWith(':scope') ? root + s.slice(6) : `${root} ${s}`))
        .join(', ')
      out += `${lead}${prefixed} {${inner}}`
    }
    i = end + 1
  }
  return out
}

let css = readFileSync(CSS, 'utf8')
const SCOPE = /@scope \(\[data-astryx-theme="ruma"\]\) to \(\[data-astryx-theme\]\) \{/
let m
let n = 0
while ((m = SCOPE.exec(css))) {
  const open = m.index + m[0].length - 1
  const end = close(css, open)
  css = css.slice(0, m.index) + prefixRules(css.slice(open + 1, end), ':where([data-astryx-theme="ruma"])') + css.slice(end + 1)
  n++
}
css = css.replace(' * @generated by `astryx theme build`', ' * @generated by `npm run theme` (astryx theme build, then @scope flattened for Safari < 17.4)')
writeFileSync(CSS, css)
console.log(`[ok] ${CSS}: ${n} @scope blocks flattened`)
