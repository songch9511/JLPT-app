// Builds the "ruma" Astryx theme (src/themes/ruma/rumaTheme.ts → ruma.css + ruma.js) with the Astryx CLI, then makes
// the stylesheet work on Safari 16.4–17.3 (the app's oldest supported iOS, docs/design-system.md §업그레이드):
//
// `astryx theme build` wraps every rule in `@scope ([data-astryx-theme="ruma"]) to ([data-astryx-theme])`, and Safari
// only has @scope from 17.4; older versions drop the whole block, so every token would fall back to Astryx's defaults.
// The app has one theme and never nests one, so the scope's lower bound never applies and each block is the same as
// its rules prefixed with `:where([data-astryx-theme="ruma"])` (`:where` keeps the specificity @scope gives them).
// `light-dark()` in the output needs no work here: Vite's CSS minifier (Lightning CSS, target safari16.4) lowers it.
//
// It then writes the two pieces of Astryx's own stylesheet (@astryxdesign/core/astryx.css, ~41 KB gzip for every
// component) that the app needs, so it never loads the whole file (docs/design-system.md §9):
// - astryx-tokens.css: the default tokens (`:root` rules: spacing, sizes, …), loaded up front by src/main.tsx;
// - astryx-overlays.css: only the rules of the Astryx components src/components/overlays.tsx imports (dialogs, bottom
//   sheet), loaded with that lazy chunk. Astryx's CSS is StyleX's atomic classes, one rule per class, and its compiled
//   JS names every class it can apply as a string literal, so a rule is kept when every class in its selector appears
//   in the JS those components reach (followed through their relative imports). Rules without classes are kept.
//
// Usage: npm run theme   (again after an Astryx upgrade, or after changing which components overlays.tsx imports)
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'

const SRC = 'src/themes/ruma/rumaTheme.ts'
const CSS = 'src/themes/ruma/ruma.css'

execFileSync('npx', ['astryx', 'theme', 'build', SRC], { stdio: 'inherit' })

/** Index of the `}` matching the `{` at `open`. */
function close(css, open) {
  let depth = 0
  for (let i = open; i < css.length; i++) {
    if (css[i] === '{') depth++
    else if (css[i] === '}' && --depth === 0) return i
  }
  throw new Error('unbalanced braces in ' + CSS)
}

/** Splits a selector list at top-level commas (not those inside `:where(a, b)`). */
function splitList(sel) {
  const parts = []
  let depth = 0
  let start = 0
  for (let i = 0; i < sel.length; i++) {
    if (sel[i] === '(') depth++
    else if (sel[i] === ')') depth--
    else if (sel[i] === ',' && depth === 0) {
      parts.push(sel.slice(start, i).trim())
      start = i + 1
    }
  }
  parts.push(sel.slice(start).trim())
  return parts
}

/** Prefixes each top-level rule of a block body with the scope root; nested at-rules (@media) are handled inside. */
function prefixRules(body, root) {
  let out = ''
  let i = 0
  while (i < body.length) {
    const open = body.indexOf('{', i)
    if (open < 0) {
      out += body.slice(i)
      break
    }
    const end = close(body, open)
    const head = body.slice(i, open)
    const inner = body.slice(open + 1, end)
    const sel = head.trim()
    const lead = head.slice(0, head.length - head.trimStart().length)
    if (sel.startsWith('@')) out += `${lead}${sel} {${prefixRules(inner, root)}}`
    else {
      const prefixed = splitList(sel)
        .map((s) => (s === ':scope' ? root : s.startsWith(':scope') ? root + s.slice(6) : `${root} ${s}`))
        .join(', ')
      out += `${lead}${prefixed} {${inner}}`
    }
    i = end + 1
  }
  return out
}

let css = readFileSync(CSS, 'utf8')
const SCOPE = /@scope \(\[data-astryx-theme="ruma"\]\) to \(\[data-astryx-theme\]\) \{/
let m
let n = 0
while ((m = SCOPE.exec(css))) {
  const open = m.index + m[0].length - 1
  const end = close(css, open)
  css = css.slice(0, m.index) + prefixRules(css.slice(open + 1, end), ':where([data-astryx-theme="ruma"])') + css.slice(end + 1)
  n++
}
css = css.replace(' * @generated by `astryx theme build`', ' * @generated by `npm run theme` (astryx theme build, then @scope flattened for Safari < 17.4)')
writeFileSync(CSS, css)
console.log(`[ok] ${CSS}: ${n} @scope blocks flattened`)

// ── Astryx's stylesheet, split and purged ──
const CORE = 'node_modules/@astryxdesign/core'
const OVERLAYS = 'src/components/overlays.tsx'
const version = JSON.parse(readFileSync(`${CORE}/package.json`, 'utf8')).version
const components = [...readFileSync(OVERLAYS, 'utf8').matchAll(/from '@astryxdesign\/core\/([A-Za-z]+)'/g)].map((m) => m[1])

/** Every StyleX class name (x + base-36 hash) in a string literal of the JS reachable from the components. */
const used = new Set()
const seen = new Set()
const walk = (file) => {
  if (seen.has(file) || !existsSync(file)) return
  seen.add(file)
  const src = readFileSync(file, 'utf8')
  for (const lit of src.matchAll(/(["'`])((?:(?!\1)[^\n\\]|\\.)*)\1/g)) for (const c of lit[2].matchAll(/\bx[a-z0-9]{3,9}\b/g)) used.add(c[0])
  for (const imp of src.matchAll(/(?:from|import)\s*["'](\.{1,2}\/[^"']+)["']/g)) walk(resolve(dirname(file), imp[1]))
}
for (const c of new Set(components)) walk(resolve(`${CORE}/dist/${c}/index.js`))

const full = readFileSync(`${CORE}/dist/astryx.css`, 'utf8')
const layerAt = full.indexOf('@layer astryx-base {')
const layerOpen = full.indexOf('{', layerAt)
const layerBody = full.slice(layerOpen + 1, close(full, layerOpen))
if (full.slice(close(full, layerOpen) + 1).trim()) throw new Error('astryx.css has rules outside @layer astryx-base: update scripts/build-theme.mjs')
const items = []
for (let i = 0; ; ) {
  const open = layerBody.indexOf('{', i)
  if (open < 0) break
  const end = close(layerBody, open)
  items.push(layerBody.slice(i, end + 1).trim())
  i = end + 1
}
const tokens = []
const rules = []
const props = []
const frames = []
for (const it of items) {
  if (it.startsWith('@property')) props.push(it)
  else if (it.startsWith('@keyframes')) frames.push(it)
  else if (it.startsWith(':root')) tokens.push(it)
  else {
    // `@media (…){.x.x{…}}` and plain `.x:hover{…}` alike: the classes in the selector(s) before the declarations
    const sel = it.slice(0, it.lastIndexOf('{', it.indexOf('}')))
    const classes = [...sel.matchAll(/\.(x[a-z0-9]+)/g)].map((m) => m[1])
    if (classes.every((c) => used.has(c))) rules.push(it)
  }
}
const kept = rules.join('\n')
const name = (re, s) => s.match(re)[1]
const keptFrames = frames.filter((f) => kept.includes(name(/@keyframes\s+([\w-]+)/, f)))
const keptProps = props.filter((p) => [kept, ...keptFrames].some((s) => s.includes(name(/@property\s+([\w-]+)/, p))))
const head = (what) =>
  `/*\n * @generated by \`npm run theme\` from @astryxdesign/core@${version} dist/astryx.css — do not edit manually.\n * ${what}\n */\n\n@layer reset, astryx-base, astryx-theme;\n\n`
// The default tokens, without those the ruma theme sets itself (its layer wins) and those nothing reads: a token is
// kept when `var(--name` appears in the app's CSS or code, the overlays' CSS or JS, or another default token.
const rumaCss = readFileSync(CSS, 'utf8')
const rumaRoot = rumaCss.slice(rumaCss.indexOf(':where([data-astryx-theme="ruma"]) {'))
const themed = new Set([...rumaRoot.slice(0, rumaRoot.indexOf('}')).matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]))
const readers = [
  rumaCss,
  kept,
  tokens.join('\n'),
  readFileSync(`${CORE}/src/reset.css`, 'utf8'),
  ...[...seen].map((f) => readFileSync(f, 'utf8')),
  ...execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', 'src'], { encoding: 'utf8' })
    .split('\n')
    .filter((f) => /\.(css|tsx?)$/.test(f) && !f.includes('themes/ruma/astryx-'))
    .map((f) => readFileSync(f, 'utf8')),
].join('\n')
const read = new Set([...readers.matchAll(/var\(\s*(--[\w-]+)/g)].map((m) => m[1]))
let dropped = 0
const defaults = tokens
  .map((rule) => {
    const open = rule.indexOf('{')
    const decls = rule
      .slice(open + 1, rule.lastIndexOf('}'))
      .split(/;(?![^(]*\))/)
      .map((d) => d.trim())
      .filter(Boolean)
    const keep = decls.filter((d) => {
      const name = d.slice(0, d.indexOf(':')).trim()
      const ok = !themed.has(name) && read.has(name)
      if (!ok) dropped++
      return ok
    })
    return keep.length ? `${rule.slice(0, open + 1)}${keep.join(';')};}` : ''
  })
  .filter(Boolean)
writeFileSync(
  'src/themes/ruma/astryx-tokens.css',
  head("Astryx's default tokens that the app reads and the ruma theme does not set.") + `@layer astryx-base {\n${defaults.join('\n')}\n}\n`,
)
writeFileSync(
  'src/themes/ruma/astryx-overlays.css',
  head(`Only the rules of ${[...new Set(components)].join(', ')} (imported by src/components/overlays.tsx).`) +
    `@layer astryx-base {\n${[...keptProps, ...keptFrames, ...rules].join('\n')}\n}\n`,
)
console.log(`[ok] astryx-tokens.css: ${defaults.length} token rules (${dropped} unread or themed tokens left out); astryx-overlays.css: ${rules.length} of ${rules.length + items.length - tokens.length - props.length - frames.length - rules.length} rules for ${components.join(', ')} (${seen.size} modules, ${used.size} classes)`)
