"""Per-kanji Korean readings for the tag audit (docs/plan/12-tag-audit.md), from the same cached sources as
scripts/enrich/kanji-table.py, plus what that table leaves out: the old-form (kyujitai / traditional) variants
of each Japanese kanji and their Korean readings, and the Unihan kKorean romanisation as a second source.

Run (after scripts/enrich/fetch-sources.sh):
    ENRICH_CACHE=<cache> $CACHE/venv/bin/python -I scripts/audit/hanja-readings.py   (any python3 works)
Writes data/tags/audit/hanja-readings.tsv, one row per kanji in data/hanja/kanji.tsv:
    char  hangul  korean  kanjidic  variants  var_hangul
  hangul      Unihan kHangul readings of the character itself (":E" kept = Korean education-hanja reading)
  korean      Unihan kKorean romanisation (independent of kHangul; converted to Hangul by the audit script)
  kanjidic    KANJIDIC2 korean_h readings
  variants    KANJIDIC2 variant characters (jis208 / jis212 / ucs cross-references), e.g. 芸 -> 藝
  var_hangul  kHangul of each variant, "藝=예:E 秇=예" (empty if the variant has none)
Sources and licences as data/hanja/NOTICE.md (Unicode License v3; KANJIDIC2 CC BY-SA 4.0, EDRDG).
"""
import os
import sqlite3
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
CACHE = os.environ.get('ENRICH_CACHE', os.path.expanduser('~/.cache/luma-enrich'))


def jis_char(kind, code):
    try:
        if kind == 'ucs':
            return chr(int(code, 16))
        _, row, cell = (int(x) for x in code.split('-'))
        b = bytes([0xA0 + row, 0xA0 + cell])
        if kind == 'jis212':
            b = b'\x8f' + b
        return b.decode('euc_jis_2004' if kind != 'jis212' else 'euc_jp')
    except Exception:
        return None


def main():
    uni = os.path.join(CACHE, 'Unihan_Readings.txt')
    db = os.path.join(CACHE, 'jamdict.db')
    for p in (uni, db):
        if not os.path.exists(p):
            sys.exit(f'missing {p}: run scripts/enrich/fetch-sources.sh first (or set ENRICH_CACHE)')
    hangul, korean = {}, {}
    with open(uni, encoding='utf8') as fh:
        for line in fh:
            parts = line.rstrip('\n').split('\t')
            if len(parts) != 3:
                continue
            cp, field, val = parts
            if field == 'kHangul':
                hangul[chr(int(cp[2:], 16))] = val
            elif field == 'kKorean':
                korean[chr(int(cp[2:], 16))] = val
    c = sqlite3.connect(db)
    kd, var = {}, {}
    for lit, val in c.execute("select ch.literal, r.value from character ch join rm_group g on g.cid = ch.ID "
                              "join reading r on r.gid = g.ID where r.r_type = 'korean_h' order by r.rowid"):
        kd.setdefault(lit, []).append(val)
    for lit, kind, val in c.execute("select ch.literal, v.var_type, v.value from character ch join variant v on v.cid = ch.ID "
                                    "where v.var_type in ('jis208', 'jis212', 'ucs')"):
        ch = jis_char(kind, val)
        if ch and ch != lit:
            var.setdefault(lit, []).append(ch)
    chars = [l.split('\t')[0] for l in open(os.path.join(ROOT, 'data/hanja/kanji.tsv'), encoding='utf8')
             if l.strip() and not l.startswith('#')]
    out = os.path.join(ROOT, 'data/tags/audit/hanja-readings.tsv')
    with open(out, 'w', encoding='utf8') as fh:
        fh.write('# char\thangul\tkorean\tkanjidic\tvariants\tvar_hangul   (generated by scripts/audit/hanja-readings.py; '
                 'Unihan 17.0.0 Unicode License v3, KANJIDIC2 CC BY-SA 4.0 EDRDG — see data/hanja/NOTICE.md)\n')
        for ch in chars:
            vs = list(dict.fromkeys(var.get(ch, [])))
            fh.write('\t'.join([ch, hangul.get(ch, ''), korean.get(ch, ''), ' '.join(dict.fromkeys(kd.get(ch, []))),
                                ''.join(vs), ' '.join(f'{v}={hangul[v].replace(" ", ",")}' for v in vs if v in hangul)]) + '\n')
    print(f'{len(chars)} kanji -> {out}; with variants: {sum(1 for ch in chars if var.get(ch))}')


if __name__ == '__main__':
    main()
