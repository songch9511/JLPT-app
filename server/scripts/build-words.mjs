// Builds src/generated/words.ts from the app's canonical word data (../public/data/n{1..5}.json).
//
// Input rows are [expression, reading, korean, english, …] (only the first four are read; the app appends
// order/frequency/word-type columns after them, see docs/plan/08 §5); the word id today is positional:
// `<level>-<index in that level's file>` (see src/data.ts in the app). A stable-id migration is
// planned: when it lands, change `idOf()` below (and WORD_ID_PATTERN / shardOf in src/words.ts)
// and nothing else in the Worker needs to change, because the Worker only ever looks words up
// through the ids this script emits.
//
// Output: one JSON string per shard (= JLPT level), parsed lazily by the Worker on first use, plus
// a content hash so a deploy can be traced back to the exact data it shipped with.
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const dataDir = new URL('../../public/data/', import.meta.url).pathname
const outDir = new URL('../src/generated/', import.meta.url).pathname

/** The single place that decides a word's id. */
const idOf = (level, index /*, row */) => `${level}-${index}`

const MAX_FIELD = 120
// Word data is only ever placed in the prompt as data; still strip anything that could break out
// of the JSON/data framing or carry invisible instructions (control and bidi/zero-width chars).
const clean = (s) =>
  String(s ?? '')
    .replace(/[\u0000-\u001f\u007f​-‏‪-‮⁦-⁩﻿]/g, '')
    .replace(/[<>]/g, '')
    .trim()
    .slice(0, MAX_FIELD)

const shards = {}
const seen = new Set()
let total = 0
const hash = createHash('sha256')
for (const level of [1, 2, 3, 4, 5]) {
  const raw = readFileSync(`${dataDir}n${level}.json`, 'utf8')
  hash.update(raw)
  const rows = JSON.parse(raw)
  if (!Array.isArray(rows)) throw new Error(`n${level}.json is not an array`)
  const out = []
  rows.forEach((row, index) => {
    if (!Array.isArray(row) || row.length < 4) throw new Error(`n${level}.json row ${index} is malformed`)
    const [expression, reading, korean, english] = row
    const id = idOf(level, index, row)
    if (seen.has(id)) throw new Error(`duplicate word id ${id}`)
    seen.add(id)
    const w = clean(expression)
    if (!w) throw new Error(`n${level}.json row ${index} has no expression`)
    // [id, expression, reading ('' when the expression is already kana), meaning (Korean, else English)]
    out.push([id, w, clean(reading), clean(korean) || clean(english)])
  })
  shards[level] = JSON.stringify(out)
  total += out.length
}

const version = hash.digest('hex').slice(0, 12)
const body =
  `// GENERATED by scripts/build-words.mjs from public/data/n{1..5}.json. Do not edit.\n` +
  `export const WORDS_VERSION = ${JSON.stringify(version)}\n` +
  `export const WORD_COUNT = ${total}\n` +
  `/** shard (JLPT level) -> JSON string of [id, expression, reading, meaning][] */\n` +
  `export const SHARDS: Record<string, string> = {\n` +
  Object.entries(shards)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n') +
  `\n}\n`

mkdirSync(outDir, { recursive: true })
writeFileSync(`${outDir}words.ts`, body)
console.log(`build-words: ${total} words, version ${version} -> src/generated/words.ts`)
