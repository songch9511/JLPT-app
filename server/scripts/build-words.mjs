// Builds src/generated/words.ts from the app's canonical word data (../public/data/words-n{1..5}.json).
//
// Input rows are [id, expression, reading, korean, english, …] (only the first five are read; the app appends
// order/frequency/word-type columns after them, see docs/plan/08 §5). The id is the word's stable id from the
// app's registry (data/ids.json, docs/plan/08 §7: `w0k3`), written into each row by scripts/build-data.mjs; it
// does not depend on the word's position or level. The Worker only ever looks words up through these ids.
//
// Output: one JSON string per shard (`shardOf` in src/words.ts: `w` + the id's first counter digit, ~1,300 words
// each), parsed lazily by the Worker on first use, plus a content hash so a deploy can be traced back to the
// exact data it shipped with.
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const dataDir = new URL('../../public/data/', import.meta.url).pathname
const outDir = new URL('../src/generated/', import.meta.url).pathname

/** The single place that decides a word's id: the stable id the row carries. */
const idOf = (row) => row[0]
/** Must match WORD_ID_PATTERN and shardOf() in src/words.ts. */
const WORD_ID = /^w(?:[0-9a-z]{3}|[1-9a-z][0-9a-z]{3,5})$/
const shardOf = (id) => id.slice(0, 2)

const MAX_FIELD = 120
// Word data is only ever placed in the prompt as data; still strip anything that could break out
// of the JSON/data framing or carry invisible instructions (control and bidi/zero-width chars).
const clean = (s) =>
  String(s ?? '')
    .replace(/[\u0000-\u001f\u007f​-‏‪-‮⁦-⁩﻿]/g, '')
    .replace(/[<>]/g, '')
    .trim()
    .slice(0, MAX_FIELD)

const shards = {}
const seen = new Set()
let total = 0
const hash = createHash('sha256')
for (const level of [1, 2, 3, 4, 5]) {
  const raw = readFileSync(`${dataDir}words-n${level}.json`, 'utf8')
  hash.update(raw)
  const rows = JSON.parse(raw)
  if (!Array.isArray(rows)) throw new Error(`words-n${level}.json is not an array`)
  rows.forEach((row, index) => {
    if (!Array.isArray(row) || row.length < 5) throw new Error(`words-n${level}.json row ${index} is malformed`)
    const [, expression, reading, korean, english] = row
    const id = idOf(row)
    if (typeof id !== 'string' || !WORD_ID.test(id)) throw new Error(`words-n${level}.json row ${index} has no valid word id`)
    if (seen.has(id)) throw new Error(`duplicate word id ${id}`)
    seen.add(id)
    const w = clean(expression)
    if (!w) throw new Error(`words-n${level}.json row ${index} has no expression`)
    // [id, expression, reading ('' when the expression is already kana), meaning (Korean, else English), JLPT level]
    ;(shards[shardOf(id)] ??= []).push([id, w, clean(reading), clean(korean) || clean(english), level])
  })
  total += rows.length
}
for (const k of Object.keys(shards)) shards[k] = JSON.stringify(shards[k])

const version = hash.digest('hex').slice(0, 12)
const body =
  `// GENERATED by scripts/build-words.mjs from public/data/words-n{1..5}.json. Do not edit.\n` +
  `export const WORDS_VERSION = ${JSON.stringify(version)}\n` +
  `export const WORD_COUNT = ${total}\n` +
  `/** shard (\`w\` + first counter digit of the id) -> JSON string of [id, expression, reading, meaning, level][] */\n` +
  `export const SHARDS: Record<string, string> = {\n` +
  Object.entries(shards)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n') +
  `\n}\n`

mkdirSync(outDir, { recursive: true })
writeFileSync(`${outDir}words.ts`, body)
console.log(`build-words: ${total} words, version ${version} -> src/generated/words.ts`)
